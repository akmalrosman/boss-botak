-- --------------------------------------------------------------- helpers
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- Create a profile automatically when someone registers.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, full_name, phone)
  values (new.id, new.email,
          coalesce(new.raw_user_meta_data->>'full_name', ''),
          coalesce(new.raw_user_meta_data->>'phone', ''));
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users for each row execute function public.handle_new_user();

-- Users may edit their own profile but must not promote themselves to admin.
-- (Running UPDATE from the SQL editor has no auth.uid(), so it is allowed.)
create or replace function public.protect_profile()
returns trigger language plpgsql set search_path = public as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    new.role := old.role;
    new.email := old.email;
  end if;
  return new;
end $$;

drop trigger if exists protect_profile on public.profiles;
create trigger protect_profile before update on public.profiles
  for each row execute function public.protect_profile();

-- ----------------------------------------------------------- place_order
-- Pricing constants MUST match lib/core/pricing.dart and lib/config/shop_config.dart
create or replace function public.place_order(
  p_items           jsonb,
  p_fulfilment      text,
  p_address         text default '',
  p_lat             double precision default null,
  p_lng             double precision default null,
  p_scheduled_for   date default null,
  p_notes           text default '',
  p_payment_method  text default 'duitnow',
  p_customer_name   text default null,
  p_customer_phone  text default null,
  p_source          text default 'app',
  p_mark_paid       boolean default false
) returns uuid
language plpgsql security definer set search_path = public as $$
declare
  c_shop_lat        constant double precision := 1.8548;
  c_shop_lng        constant double precision := 102.9325;
  c_base_fee        constant numeric := 5;
  c_included_km     constant numeric := 5;
  c_per_km          constant numeric := 1;
  c_max_km          constant numeric := 25;
  c_free_threshold  constant numeric := 150;
  c_bulk_threshold  constant numeric := 300;
  c_bulk_rate       constant numeric := 0.05;

  v_uid        uuid := auth.uid();
  v_profile    public.profiles;
  v_owner_sale boolean;
  v_item       jsonb;
  v_product    public.products;
  v_qty        integer;
  v_subtotal   numeric := 0;
  v_fee        numeric := 0;
  v_discount   numeric := 0;
  v_km         numeric;
  v_order_id   uuid;
begin
  if v_uid is null then raise exception 'Please sign in first.'; end if;
  select * into v_profile from public.profiles where id = v_uid;
  if not found then raise exception 'Profile not found.'; end if;

  v_owner_sale := v_profile.role = 'admin' and p_source in ('whatsapp', 'walk_in');

  if p_items is null or jsonb_array_length(p_items) = 0 then
    raise exception 'Your cart is empty.';
  end if;
  if p_fulfilment not in ('pickup', 'delivery') then raise exception 'Invalid fulfilment option.'; end if;
  if p_payment_method not in ('duitnow', 'fpx') then raise exception 'Invalid payment method.'; end if;
  if v_owner_sale and coalesce(trim(p_customer_name), '') = '' then
    raise exception 'Customer name is required.';
  end if;

  if p_fulfilment = 'delivery' then
    if p_lat is null or p_lng is null or coalesce(trim(p_address), '') = '' then
      raise exception 'Please set a delivery address.';
    end if;
    v_km := 6371 * 2 * asin(sqrt(
              power(sin(radians(p_lat - c_shop_lat) / 2), 2) +
              cos(radians(c_shop_lat)) * cos(radians(p_lat)) *
              power(sin(radians(p_lng - c_shop_lng) / 2), 2)));
    if v_km > c_max_km then
      raise exception 'Sorry, this address is outside our delivery area.';
    end if;
  end if;

  insert into public.orders (
    customer_id, customer_name, customer_phone, fulfilment, address, lat, lng,
    distance_km, scheduled_for, notes, payment_method, payment_status, status, source)
  values (
    case when v_owner_sale then null else v_uid end,
    case when v_owner_sale then trim(p_customer_name) else v_profile.full_name end,
    case when v_owner_sale then coalesce(trim(p_customer_phone), '') else v_profile.phone end,
    p_fulfilment,
    case when p_fulfilment = 'delivery' then trim(p_address) else '' end,
    case when p_fulfilment = 'delivery' then p_lat end,
    case when p_fulfilment = 'delivery' then p_lng end,
    round(v_km, 1),
    p_scheduled_for,
    left(coalesce(p_notes, ''), 300),
    p_payment_method,
    case when v_owner_sale and p_mark_paid then 'paid' else 'unpaid' end,
    case when v_owner_sale then 'confirmed' else 'pending' end,
    case when v_owner_sale then p_source else 'app' end)
  returning id into v_order_id;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    if v_qty is null or v_qty <= 0 then raise exception 'Invalid quantity.'; end if;

    -- Lock the product row so two customers cannot buy the last pack.
    select * into v_product from public.products
      where id = (v_item->>'product_id')::uuid and is_active
      for update;
    if not found then raise exception 'A product in your cart is no longer available.'; end if;
    if v_product.stock < v_qty then
      raise exception 'Sorry, only % left for %.', v_product.stock, v_product.name;
    end if;

    update public.products set stock = stock - v_qty where id = v_product.id;
    insert into public.order_items (order_id, product_id, product_name, unit_price, unit_cost, quantity)
      values (v_order_id, v_product.id, v_product.name, v_product.price, v_product.cost, v_qty);
    v_subtotal := v_subtotal + v_product.price * v_qty;
  end loop;

  if p_fulfilment = 'delivery' and v_subtotal < c_free_threshold then
    v_fee := c_base_fee + ceil(greatest(0, v_km - c_included_km)) * c_per_km;
  end if;
  if v_subtotal >= c_bulk_threshold then
    v_discount := round(v_subtotal * c_bulk_rate, 2);
  end if;

  update public.orders
     set subtotal = v_subtotal, delivery_fee = v_fee, discount = v_discount,
         total = v_subtotal - v_discount + v_fee
   where id = v_order_id;

  return v_order_id;
end $$;

-- ------------------------------------------------------ set_order_status
create or replace function public.set_order_status(p_order_id uuid, p_status text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_order public.orders;
  v_admin boolean := public.is_admin();
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found or (not v_admin and v_order.customer_id is distinct from auth.uid()) then
    raise exception 'Order not found.';
  end if;
  if p_status not in ('pending','confirmed','preparing','ready','completed','cancelled') then
    raise exception 'Invalid status.';
  end if;
  if not v_admin and not (p_status = 'cancelled' and v_order.status = 'pending') then
    raise exception 'You can only cancel an order while it is pending.';
  end if;
  if v_order.status in ('completed', 'cancelled') then
    raise exception 'This order is already %.', v_order.status;
  end if;

  if p_status = 'cancelled' then
    update public.products p
       set stock = p.stock + s.qty
      from (select product_id, sum(quantity) as qty
              from public.order_items where order_id = p_order_id group by product_id) s
     where s.product_id = p.id;
  end if;

  update public.orders set status = p_status, updated_at = now() where id = p_order_id;
end $$;

-- ------------------------------------------------------ payments (DuitNow / FPX)
-- Customer attached a DuitNow receipt -> wait for the owner to verify.
create or replace function public.submit_payment_receipt(p_order_id uuid, p_receipt_path text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_order public.orders;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found or v_order.customer_id is distinct from auth.uid() then
    raise exception 'Order not found.';
  end if;
  if v_order.status = 'cancelled' then raise exception 'This order was cancelled.'; end if;
  if v_order.payment_status = 'paid' then raise exception 'This order is already paid.'; end if;
  -- the file must be inside the customer's own folder of the private bucket
  if split_part(p_receipt_path, '/', 1) <> auth.uid()::text then
    raise exception 'Invalid receipt file.';
  end if;
  update public.orders
     set receipt_url = p_receipt_path, payment_method = 'duitnow',
         payment_status = 'pending_verification', updated_at = now()
   where id = p_order_id;
end $$;

-- Owner approves (paid) or rejects (back to unpaid) a DuitNow receipt.
create or replace function public.review_payment_receipt(p_order_id uuid, p_approve boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'You are not allowed to do that.'; end if;
  update public.orders
     set payment_status = case when p_approve then 'paid' else 'unpaid' end,
         payment_ref    = case when p_approve then 'DuitNow receipt verified' else payment_ref end,
         receipt_url    = case when p_approve then receipt_url else null end,
         updated_at     = now()
   where id = p_order_id and payment_status = 'pending_verification';
  if not found then raise exception 'There is no receipt waiting to be checked.'; end if;
end $$;

-- FPX SANDBOX: simulates a successful online-banking payment for the
-- prototype. Replace with a real FPX gateway callback before going live.
create or replace function public.simulate_fpx_payment(p_order_id uuid, p_bank text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_order public.orders;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found or v_order.customer_id is distinct from auth.uid() then
    raise exception 'Order not found.';
  end if;
  if v_order.status = 'cancelled' then raise exception 'This order was cancelled.'; end if;
  if v_order.payment_status = 'paid' then raise exception 'This order is already paid.'; end if;
  update public.orders
     set payment_status = 'paid', payment_method = 'fpx', receipt_url = null,
         payment_ref = 'FPX' || to_char(now(), 'YYMMDDHH24MISS') || ' · ' || left(p_bank, 40),
         updated_at = now()
   where id = p_order_id;
end $$;

-- ----------------------------------------------------------- adjust_stock
create or replace function public.adjust_stock(p_product_id uuid, p_delta integer)
returns public.products language plpgsql security definer set search_path = public as $$
declare
  v_product public.products;
begin
  if not public.is_admin() then raise exception 'You are not allowed to do that.'; end if;
  select * into v_product from public.products where id = p_product_id for update;
  if not found then raise exception 'Product not found.'; end if;
  if v_product.stock + p_delta < 0 then raise exception 'Stock cannot go below zero.'; end if;
  update public.products set stock = stock + p_delta where id = p_product_id
    returning * into v_product;
  return v_product;
end $$;

