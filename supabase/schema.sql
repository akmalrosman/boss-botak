-- =====================================================================
-- Boss Botak - Supabase (PostgreSQL) schema
-- Run this whole file once in Supabase Dashboard > SQL Editor.
--
-- Security model
--   * Row Level Security (RLS) on every table
--   * customers see only their own profile/orders; the owner (role=admin)
--     manages products, orders, expenses and sees all customers
--   * orders are created ONLY through place_order(), which re-reads prices
--     from the database, checks stock atomically and computes fees on the
--     server (the app cannot tamper with prices or totals)
-- =====================================================================

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- tables
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  email       text,
  full_name   text not null default '',
  phone       text not null default '',
  role        text not null default 'customer' check (role in ('customer', 'admin')),
  address     text not null default '',
  lat         double precision,
  lng         double precision,
  created_at  timestamptz not null default now()
);

create table if not exists public.products (
  id                  uuid primary key default gen_random_uuid(),
  name                text not null,
  description         text not null default '',
  category            text not null default 'Otak-Otak',
  unit                text not null default '1 pack',
  price               numeric(10,2) not null check (price >= 0),
  cost                numeric(10,2) not null default 0 check (cost >= 0),
  stock               integer not null default 0 check (stock >= 0),
  low_stock_threshold integer not null default 10 check (low_stock_threshold >= 0),
  image_url           text not null default '',
  is_active           boolean not null default true,
  created_at          timestamptz not null default now()
);

create table if not exists public.orders (
  id                uuid primary key default gen_random_uuid(),
  order_no          bigint generated by default as identity (start with 1001) unique,
  customer_id       uuid references public.profiles(id) on delete set null,
  customer_name     text not null,
  customer_phone    text not null default '',
  subtotal          numeric(10,2) not null default 0,
  delivery_fee      numeric(10,2) not null default 0,
  discount          numeric(10,2) not null default 0,
  total             numeric(10,2) not null default 0,
  fulfilment        text not null check (fulfilment in ('pickup', 'delivery')),
  address           text not null default '',
  lat               double precision,
  lng               double precision,
  distance_km       numeric(6,1),
  scheduled_for     date,
  notes             text not null default '',
  payment_method    text not null default 'duitnow' check (payment_method in ('duitnow', 'fpx')),
  payment_status    text not null default 'unpaid'
                    check (payment_status in ('unpaid', 'pending_verification', 'paid')),
  payment_ref       text,
  receipt_url       text,   -- storage path of the DuitNow receipt (private bucket)
  status            text not null default 'pending'
                    check (status in ('pending','confirmed','preparing','ready','completed','cancelled')),
  source            text not null default 'app' check (source in ('app', 'whatsapp', 'walk_in')),
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create table if not exists public.order_items (
  id           uuid primary key default gen_random_uuid(),
  order_id     uuid not null references public.orders(id) on delete cascade,
  product_id   uuid references public.products(id) on delete set null,
  product_name text not null,
  unit_price   numeric(10,2) not null,
  unit_cost    numeric(10,2) not null default 0,
  quantity     integer not null check (quantity > 0)
);

create table if not exists public.expenses (
  id          uuid primary key default gen_random_uuid(),
  title       text not null,
  category    text not null default 'Other',
  amount      numeric(10,2) not null check (amount > 0),
  spent_on    date not null default current_date,
  note        text not null default '',
  created_by  uuid references public.profiles(id) on delete set null,
  created_at  timestamptz not null default now()
);

